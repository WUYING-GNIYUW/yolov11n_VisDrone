import argparse
import contextlib
import csv
import gc
import json
import math
import os
import shlex
import sys
import traceback
from pathlib import Path

from .__main__ import train, validate
from .config import BASE, bits_of, combinations, from_id
from .records import file_hash, write_json


def main():
    p = argparse.ArgumentParser(description='Train and reload every switch combination on the small engineering-only fixture')
    p.add_argument('--data', required=True, type=Path)
    p.add_argument('--project', required=True, type=Path, help='new directory for checkpoints and logs')
    p.add_argument('--output', required=True, type=Path)
    p.add_argument('--ids', nargs='+')
    p.add_argument('--imgsz', type=int, default=96)
    args = p.parse_args()
    os.environ.setdefault('YOLO_OFFLINE', 'true')
    os.environ.setdefault('YOLO_AUTOINSTALL', 'false')
    import torch
    torch.set_num_threads(1)
    import ultralytics
    from ultralytics.utils import LOGGER
    import logging
    data = args.data.resolve(strict=True)
    manifest_path = data.parent / 'manifest.json'
    fixture = json.loads(manifest_path.read_text())
    if not fixture.get('purpose', '').startswith('engineering smoke only'):
        p.error('use the engineering-only fixture generated by dronebench.evaluation.smoke_data')
    args.project.mkdir(parents=True, exist_ok=False)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    selections = list(dict.fromkeys(args.ids)) if args.ids else [bits_of(s) for s in combinations()]
    report = {'scope': 'real-image engineering smoke, not a benchmark', 'baseline': BASE,
              'torch': str(torch.__version__), 'ultralytics': ultralytics.__version__, 'device': 'cpu',
              'fixture': fixture, 'imgsz': args.imgsz, 'epochs': 1, 'batch': 2, 'seed': 0,
              'command': shlex.join([sys.executable, '-m', 'dronebench.e2e_smoke', *sys.argv[1:]]), 'rows': []}
    for bits in selections:
        from_id(bits)
        folder = args.project / bits
        folder.mkdir()
        log = folder / 'smoke.log'
        print(f'{bits}: {log}', flush=True)
        rec = {'id': bits, 'status': 'failed'}
        try:
            with log.open('w') as f, contextlib.redirect_stdout(f), contextlib.redirect_stderr(f):
                handler = logging.StreamHandler(f)
                original = LOGGER.handlers[:]
                LOGGER.handlers = [handler]
                try:
                    common = dict(data=str(data), batch=2, imgsz=args.imgsz, device='cpu')
                    a = argparse.Namespace(id=bits, config=None, **common, epochs=1, workers=0, seed=0,
                                           kind='smoke', init=None, project=folder)
                    train(a)
                    receipt_path, = folder.glob('*/experiment.json')
                    receipt = json.loads(receipt_path.read_text())
                    valpath = receipt_path.parent / 'reloaded.json'
                    validate(argparse.Namespace(weights=receipt['best'], **common, split='val', output=str(valpath)))
                finally:
                    LOGGER.handlers = original
            val = json.loads(valpath.read_text())
            with (receipt_path.parent / 'results.csv').open() as f:
                row, = csv.DictReader(f)
            losses = {k: float(v) for k, v in row.items() if k.startswith(('train/', 'val/'))}
            if not (receipt['status'] == 'trained' and receipt['optimizer_steps'] > 0 and receipt['completed_epochs'] == 1 and losses and all(map(math.isfinite, losses.values()))):
                raise RuntimeError('missing update or nonfinite loss')
            if val['images'] != len(fixture['splits']['val']) or sum(b['gt'] for b in val['bins'].values()) != sum(g['gt'] for g in fixture['splits']['val']):
                raise RuntimeError('incomplete validation split, examples or GT missing')
            rec.update(status='passed', train_val_reload=True, images=val['images'],
                       validation_gt={k: b['gt'] for k, b in val['bins'].items()}, losses=losses,
                       actual_optimizer_steps=receipt['optimizer_steps'], effective_batch=receipt['effective_batch'],
                       checkpoint_sha256=file_hash(receipt['best']), source_sha256=receipt['source_sha256'])
        except Exception:
            rec['error'] = traceback.format_exc()
            print(rec['error'], file=sys.stderr)
        finally:
            gc.collect()
        report['rows'].append(rec)
        write_json(args.output, report)
    failed = sum(r['status'] != 'passed' for r in report['rows'])
    print(f'{len(selections)-failed}/{len(selections)} passed; {args.output}')
    return int(failed != 0)


if __name__ == '__main__':
    raise SystemExit(main())
